"""Build the results report from the result files, and only from them.

Reads:
- `results/verifier_eval.json` (from `groundcheck eval-verifiers`), plus a listing of
  any other `results/*.json`;
- `data/eval/results/*.json` (from `groundcheck eval-retrieval`, one per embedder);
- the label file and candidates, for the class-balance table of the dataset card.

Writes:
- `docs/RESULTS.md`, regenerated in full: retrieval table, verifier comparison table
  (accuracy, macro-F1, supported-vs-not accuracy, latency p50/p95, cost: "$0 (local)"
  for every local verifier, hosted rows only as clearly labeled estimates), confusion
  matrices as Markdown tables, per-edge-case and per-mode accuracy, and the charts;
- the section of `README.md` between `<!-- RESULTS:START -->` and `<!-- RESULTS:END -->`,
  but only when both the retrieval and the verifier results exist. Otherwise the
  report prints what is missing and leaves the README markers untouched;
- the class-balance table between `<!-- BALANCE:START -->` / `<!-- BALANCE:END -->` in
  `docs/DATASET_CARD.md`, from the confirmed labels (left alone if there are none);
- `docs/figures/accuracy_vs_latency.png` and `docs/figures/edge_case_accuracy.png`
  (needs the `[report]` extra, i.e. matplotlib; without it the charts are skipped and
  the tables are still written).

Every number printed comes from a file; nothing is estimated except the hosted cost,
which `eval-verifiers` computed and labeled as an estimate. A missing input is written
as "not run yet" with the command that produces it, never as a number.
"""

from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

from pydantic import ValidationError

from groundcheck.config import REPO_ROOT
from groundcheck.labeling.schema import LABELS
from groundcheck.retrieval.evaluate import RetrievalReport
from groundcheck.verify.evaluate import EvalResults, VerifierReport

RESULTS_START = "<!-- RESULTS:START -->"
RESULTS_END = "<!-- RESULTS:END -->"
BALANCE_START = "<!-- BALANCE:START -->"
BALANCE_END = "<!-- BALANCE:END -->"
DEFAULT_DOCS_DIR = REPO_ROOT / "docs"
DEFAULT_README = REPO_ROOT / "README.md"
GENERATED_NOTE = (
    "<!-- Generated by `groundcheck report` from the result files; do not edit by hand. -->"
)

# Chart colors: the dataviz skill's validated categorical order (light mode) and inks.
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"


@dataclass
class Inputs:
    verifier: EvalResults | None = None
    verifier_path: Path | None = None
    retrieval: dict[str, RetrievalReport] = field(default_factory=dict)  # file name -> report
    other_results: list[str] = field(default_factory=list)
    balance: dict | None = None  # see class_balance()
    missing: list[str] = field(default_factory=list)  # "what: how to make it"
    problems: list[str] = field(default_factory=list)


def _show(path: Path) -> str:
    """A path as written in reports: relative to the repo when inside it (no home dirs)."""
    try:
        return str(Path(path).resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _ms(x: float) -> str:
    return f"{x:,.0f} ms" if x >= 10 else f"{x:.1f} ms"


def load_inputs(
    results_dir: Path,
    retrieval_dir: Path,
    labels_path: Path | None = None,
    candidates_dir: Path | None = None,
) -> Inputs:
    inputs = Inputs()
    path = results_dir / "verifier_eval.json"
    if path.is_file():
        try:
            results = EvalResults.model_validate_json(path.read_text())
        except ValidationError as exc:
            inputs.problems.append(f"{_show(path)} is not a valid verifier_eval.json: {exc}")
        else:
            if results.verifiers:
                inputs.verifier, inputs.verifier_path = results, path
            else:
                inputs.missing.append(
                    f"{_show(path)} has no verifier entries: run groundcheck eval-verifiers"
                )
    else:
        inputs.missing.append(
            f"verifier results ({_show(path)}): run `groundcheck eval-verifiers --verifier ...` "
            "after `groundcheck export-labels`"
        )
    if results_dir.is_dir():
        inputs.other_results = sorted(
            p.name for p in results_dir.glob("*.json") if p.name != "verifier_eval.json"
        )
    for p in sorted(retrieval_dir.glob("*.json")) if retrieval_dir.is_dir() else []:
        try:
            inputs.retrieval[p.name] = RetrievalReport.model_validate_json(p.read_text())
        except ValidationError:
            inputs.problems.append(f"{_show(p)} is not a retrieval report; skipped")
    if not inputs.retrieval:
        inputs.missing.append(
            f"retrieval results ({_show(retrieval_dir)}/*.json): run `groundcheck eval-retrieval`"
        )
    if labels_path is not None:
        inputs.balance = class_balance(labels_path, candidates_dir)
    return inputs


def class_balance(labels_path: Path, candidates_dir: Path | None) -> dict | None:
    """Confirmed, valid (not `x`-invalid) labels by mode x label, from the label file."""
    from groundcheck.labeling.store import LabelStore, load_candidates

    if not labels_path.is_file():
        return None
    try:
        records = [r for r in LabelStore(labels_path).records.values() if r.confirmed]
    except Exception:  # an invalid label file: label-check reports it, not the report
        return None
    candidates = load_candidates(candidates_dir) if candidates_dir else []
    mode_of = {c.candidate_id: c.mode for c in candidates}
    valid = [r for r in records if not r.invalid]
    if not valid:
        return None
    table = Counter((mode_of.get(r.candidate_id, "(unknown)"), r.label) for r in valid)
    return {
        "modes": sorted({m for m, _ in table}),
        "counts": {f"{m}|{label}": n for (m, label), n in table.items()},
        "total": len(valid),
        "invalid": sum(r.invalid for r in records),
        "companies": len({r.ticker for r in valid}),
    }


# --- Markdown -----------------------------------------------------------------------


def retrieval_table(inputs: Inputs) -> list[str]:
    if not inputs.retrieval:
        return ["*Not run yet:* `groundcheck eval-retrieval` writes `data/eval/results/`.", ""]
    ks = sorted({k for r in inputs.retrieval.values() for k in r.ks})
    lines = [
        "| Embedder | Chunker | Questions | "
        + " | ".join(f"Recall@{k}" for k in ks)
        + " | "
        + " | ".join(f"Section hit@{k}" for k in ks)
        + " |",
        "|---|---|---|" + "---|" * (2 * len(ks)),
    ]
    for report in inputs.retrieval.values():
        o = report.overall
        lines.append(
            f"| `{report.embedder}` | `{report.chunker}` | {o.n} | "
            + " | ".join(_pct(o.recall.get(k)) for k in ks)
            + " | "
            + " | ".join(_pct(o.section_hit.get(k)) for k in ks)
            + " |"
        )
    lines += [
        "",
        "Recall@k: share of the gold evidence strings found in the top k chunks; section "
        "hit@k: a top-k chunk comes from the gold Item. Unanswerable and unfilled "
        "questions are excluded.",
        "",
    ]
    return lines


def _cost(report: VerifierReport) -> str:
    if report.local:
        return "$0 (local)"
    return "n/a"


def verifier_table(results: EvalResults | None) -> list[str]:
    if results is None:
        return [
            "*Not run yet:* `groundcheck eval-verifiers` writes `results/verifier_eval.json` "
            "from the confirmed gold labels.",
            "",
        ]
    reports = list(results.verifiers.values())
    lines = []
    shas = {r.gold_sha256 for r in reports}
    first = reports[0]
    lines += [
        f"Gold set: {first.n} confirmed claim(s), `{Path(first.gold_file).name}` "
        f"(sha256 `{first.gold_sha256[:12]}`).",
        "",
    ]
    if len(shas) > 1:
        lines += [
            "> **Warning:** these rows were computed on different gold files; re-run "
            "`eval-verifiers` for all verifiers before comparing them.",
            "",
        ]
    lines += [
        "| Verifier | Model | Accuracy | Macro-F1 | Supported vs not (acc.) | Latency p50 "
        "| Latency p95 | Cost / 1,000 checks |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in reports:
        lines.append(
            f"| {r.verifier} | `{r.identity.get('model', '')}` | {_pct(r.accuracy)} | "
            f"{r.macro_f1:.3f} | {_pct(r.binary.accuracy)} | {_ms(r.latency.p50_ms)} | "
            f"{_ms(r.latency.p95_ms)} | {_cost(r)} |"
        )
    for estimate in results.hosted_cost_estimates:
        lines.append(
            f"| hosted judge (**estimate only, not run**) | `{estimate.model}` | not run | "
            f"not run | not run | not run | not run | ~{estimate.cost_per_1000_checks:.2f} "
            f"{estimate.currency} (**estimate**) |"
        )
    lines += [
        "",
        "Accuracy and macro-F1 are over three labels (supported, contradicted, "
        "unsupported). *Supported vs not* merges contradicted and unsupported; it is the "
        "fair column for MiniCheck and HHEM, which are binary and never predict "
        "contradicted. Latency is per claim, all retrieved passages, on the machine that "
        "ran the evaluation. Every verifier here runs locally, so it costs $0; a hosted "
        "row, if present, is arithmetic from `config/prices.yaml`, never a call.",
        "",
    ]
    if results.hosted_cost_note:
        lines += [f"*Cost estimate:* {results.hosted_cost_note}", ""]
    return lines


def confusion_tables(results: EvalResults | None) -> list[str]:
    if results is None:
        return []
    lines = []
    for r in results.verifiers.values():
        lines += [
            f"### {r.verifier}",
            "",
            "Confusion matrix (rows: gold label, columns: predicted label):",
            "",
            "| gold \\ predicted | " + " | ".join(LABELS) + " | total |",
            "|---" * (len(LABELS) + 2) + "|",
        ]
        for g in LABELS:
            row = [r.confusion.get(g, {}).get(p, 0) for p in LABELS]
            lines.append(f"| {g} | " + " | ".join(map(str, row)) + f" | {sum(row)} |")
        lines += ["", "| Label | Precision | Recall | F1 | Gold n |", "|---|---|---|---|---|"]
        for label, m in r.per_class.items():
            lines.append(
                f"| {label} | {_pct(m.precision)} | {_pct(m.recall)} | {m.f1:.3f} | {m.support} |"
            )
        lines.append("")
    return lines


def group_table(results: EvalResults | None, attr: str, title: str) -> list[str]:
    if results is None:
        return []
    reports = list(results.verifiers.values())
    keys = sorted({k for r in reports for k in getattr(r, attr)})
    if not keys:
        return []
    lines = [
        f"| {title} | " + " | ".join(r.verifier for r in reports) + " |",
        "|---" * (len(reports) + 1) + "|",
    ]
    for key in keys:
        cells = []
        for r in reports:
            g = getattr(r, attr).get(key)
            cells.append(f"{_pct(g.accuracy)} (n={g.n})" if g else "-")
        lines.append(f"| {key} | " + " | ".join(cells) + " |")
    return [*lines, ""]


def balance_table(balance: dict | None) -> list[str]:
    if not balance:
        return ["*No confirmed labels yet:* run `groundcheck label`, then `groundcheck report`."]
    lines = [
        "| Mode | " + " | ".join(LABELS) + " | total |",
        "|---" * (len(LABELS) + 2) + "|",
    ]
    totals = Counter()
    for mode in balance["modes"]:
        row = [balance["counts"].get(f"{mode}|{label}", 0) for label in LABELS]
        totals.update(dict(zip(LABELS, row, strict=True)))
        lines.append(f"| {mode} | " + " | ".join(map(str, row)) + f" | {sum(row)} |")
    total = balance["total"]
    lines.append(
        "| **all** | "
        + " | ".join(f"{totals[label]} ({totals[label] / total:.0%})" for label in LABELS)
        + f" | {total} |"
    )
    lines += [
        "",
        f"Confirmed labels from {balance['companies']} company(ies); "
        f"{balance['invalid']} claim(s) marked invalid are not counted.",
    ]
    return lines


def results_markdown(inputs: Inputs, figures: list[str]) -> str:
    lines = [
        "# Results",
        "",
        GENERATED_NOTE,
        "",
        "Every number below is read from a result file written by a real run; nothing "
        "is filled in by hand. Re-generate with `groundcheck report`.",
        "",
    ]
    if inputs.missing:
        lines += ["**Not run yet:**", ""] + [f"- {m}" for m in inputs.missing] + [""]
    lines += ["## Retrieval", "", *retrieval_table(inputs)]
    lines += ["## Verifier comparison", "", *verifier_table(inputs.verifier)]
    if inputs.verifier is not None:
        lines += ["## Accuracy by edge case", ""]
        lines += group_table(inputs.verifier, "by_edge_case", "Edge case")
        lines += ["## Accuracy by generation mode", ""]
        lines += group_table(inputs.verifier, "by_mode", "Mode") or ["No mode breakdown.", ""]
        lines += ["## Accuracy by company", ""]
        lines += group_table(inputs.verifier, "by_company", "Company")
        lines += ["## Confusion matrices", "", *confusion_tables(inputs.verifier)]
    if figures:
        lines += ["## Charts", ""] + [f"![{Path(f).stem}](figures/{Path(f).name})" for f in figures]
        lines.append("")
    lines += ["## Gold set class balance", "", *balance_table(inputs.balance), ""]
    if inputs.other_results:
        lines += [
            "Other result files present: " + ", ".join(f"`{n}`" for n in inputs.other_results),
            "",
        ]
    return "\n".join(lines)


def readme_section(inputs: Inputs) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "### Retrieval",
        "",
        *retrieval_table(inputs),
        "### Verifier benchmark",
        "",
        *verifier_table(inputs.verifier),
        "Confusion matrices, per-edge-case and per-mode accuracy and charts: "
        "[docs/RESULTS.md](docs/RESULTS.md).",
    ]
    return "\n".join(lines)


def replace_between(text: str, start: str, end: str, body: str) -> str | None:
    """`text` with everything between the markers replaced, or None if they're absent."""
    i, j = text.find(start), text.find(end)
    if i < 0 or j < 0 or j < i:
        return None
    return text[: i + len(start)] + "\n" + body.rstrip() + "\n" + text[j:]


# --- charts -------------------------------------------------------------------------


def _pyplot():
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return None
    return plt


def _style(ax) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK_2, labelsize=9)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def write_charts(results: EvalResults, figures_dir: Path, plt=None) -> list[str]:
    """The two PNGs; returns their paths (empty if matplotlib is not installed)."""
    plt = plt or _pyplot()
    if plt is None:
        return []
    figures_dir.mkdir(parents=True, exist_ok=True)
    reports = list(results.verifiers.values())
    out = []

    fig, ax = plt.subplots(figsize=(7, 4.2), dpi=150, facecolor=SURFACE)
    _style(ax)
    for i, r in enumerate(reports):
        color = SERIES[i % len(SERIES)]
        ax.scatter([r.latency.p50_ms], [100 * r.accuracy], s=70, color=color,
                   edgecolors=SURFACE, linewidths=2, zorder=3, label=r.verifier)  # fmt: skip
        ax.annotate(r.verifier, (r.latency.p50_ms, 100 * r.accuracy), xytext=(7, 4),
                    textcoords="offset points", fontsize=9, color=INK)  # fmt: skip
    ax.set_xscale("log")
    ax.set_xlabel("Latency per claim, p50 (ms, log scale)", color=INK_2, fontsize=9)
    ax.set_ylabel("Accuracy, three labels (%)", color=INK_2, fontsize=9)
    ax.set_title("Accuracy vs latency", color=INK, fontsize=11, loc="left")
    ax.legend(frameon=False, fontsize=8, labelcolor=INK_2, loc="upper left",
              bbox_to_anchor=(1.01, 1.0))  # fmt: skip
    fig.tight_layout()
    path = figures_dir / "accuracy_vs_latency.png"
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)
    out.append(str(path))

    tags = sorted({t for r in reports for t in r.by_edge_case})
    if tags:
        fig, ax = plt.subplots(figsize=(9, 4.6), dpi=150, facecolor=SURFACE)
        _style(ax)
        ax.grid(False, axis="x")
        width = 0.8 / max(len(reports), 1)
        for i, r in enumerate(reports):
            offset = (i - (len(reports) - 1) / 2) * width
            present = [(t, tag) for t, tag in enumerate(tags) if tag in r.by_edge_case]
            xs = [t + offset for t, _ in present]
            ys = [100 * r.by_edge_case[tag].accuracy for _, tag in present]
            ax.bar(xs, ys, width=width * 0.9, color=SERIES[i % len(SERIES)],
                   edgecolor=SURFACE, linewidth=1, label=r.verifier)  # fmt: skip
        n = {tag: max(r.by_edge_case[tag].n for r in reports if tag in r.by_edge_case)
             for tag in tags}  # fmt: skip
        ax.set_xticks(range(len(tags)))
        ax.set_xticklabels([f"{t}\n(n={n[t]})" for t in tags], fontsize=8)
        ax.set_ylim(0, 100)
        ax.set_ylabel("Accuracy (%)", color=INK_2, fontsize=9)
        ax.set_title("Accuracy by edge-case tag (a 0% bar is drawn as nothing)", color=INK,
                     fontsize=11, loc="left", pad=24)  # fmt: skip
        ax.legend(frameon=False, fontsize=8, labelcolor=INK_2, ncols=min(len(reports), 4),
                  loc="lower left", bbox_to_anchor=(0, 1.0))  # fmt: skip
        fig.tight_layout()
        path = figures_dir / "edge_case_accuracy.png"
        fig.savefig(path, facecolor=SURFACE)
        plt.close(fig)
        out.append(str(path))
    return out


# --- the command --------------------------------------------------------------------


@dataclass
class ReportOutcome:
    results_md: Path
    readme_updated: bool
    figures: list[str]
    missing: list[str]
    messages: list[str]


def build_report(
    results_dir: Path,
    retrieval_dir: Path,
    readme: Path = DEFAULT_README,
    docs_dir: Path = DEFAULT_DOCS_DIR,
    labels_path: Path | None = None,
    candidates_dir: Path | None = None,
    plt=None,
) -> ReportOutcome:
    inputs = load_inputs(results_dir, retrieval_dir, labels_path, candidates_dir)
    messages = list(inputs.problems)
    figures: list[str] = []
    if inputs.verifier is not None:
        figures = write_charts(inputs.verifier, docs_dir / "figures", plt)
        if not figures:
            messages.append(
                'charts skipped: matplotlib is not installed (pip install -e ".[report]")'
            )
    docs_dir.mkdir(parents=True, exist_ok=True)
    results_md = docs_dir / "RESULTS.md"
    results_md.write_text(results_markdown(inputs, figures))

    readme_updated = False
    if inputs.missing:
        messages.append("README.md results section left untouched: inputs are missing.")
    elif readme.is_file():
        new = replace_between(
            readme.read_text(), RESULTS_START, RESULTS_END, readme_section(inputs)
        )
        if new is None:
            messages.append(
                f"{readme} has no {RESULTS_START} / {RESULTS_END} markers; not changed."
            )
        else:
            readme.write_text(new)
            readme_updated = True

    card = docs_dir / "DATASET_CARD.md"
    if inputs.balance and card.is_file():
        body = "\n".join(balance_table(inputs.balance))
        new = replace_between(card.read_text(), BALANCE_START, BALANCE_END, body)
        if new is not None:
            card.write_text(new)
            messages.append(f"Updated the class-balance table in {card}.")
    return ReportOutcome(results_md, readme_updated, figures, inputs.missing, messages)
